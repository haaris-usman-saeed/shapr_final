#!/usr/bin/env node
// Writes script.md (timed narration for every film) from timeline.json + the narration manifest,
// so the human-read script can never drift from the picture.   node scripts/docs.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tl = JSON.parse(fs.readFileSync(path.join(ROOT, "timeline.json"), "utf8"));
let man = { durations: {}, source: {} };
try { man = JSON.parse(fs.readFileSync(path.join(ROOT, "assets/audio/narration/manifest.json"), "utf8")); } catch {}
const mmss = (s) => `${Math.floor(s / 60)}:${(s % 60).toFixed(1).padStart(4, "0")}`;

let md = `# Narration script

Generated by \`node scripts/docs.mjs\` from \`timeline.json\`. Times are from the start of each film.
"Shapr" is said **"shaper"**. Read like you're showing a friend something useful: short sentences, no hype,
and leave the silences (before the circle, before the memory card, before the end card).

**Recording a human read.** Record each line as its own file named by its id (for example \`n03b.wav\`),
put the files in \`assets/audio/narration/human/\`, then run \`npm run audio\` and \`npm run assemble:hero\`.
A line may run up to the "room" shown; longer reads should move the next cue in \`timeline.json\`.

`;
for (const [key, film] of Object.entries(tl.films)) {
  md += `\n## ${film.title}\n\n| Time | Id | Line | Synth length | Room |\n|---|---|---|---|---|\n`;
  let t0 = 0;
  const rows = [];
  for (const e of film.entries) {
    const base = tl.scenes[e.scene] || {};
    const from = e.from || 0;
    const narr = (e.narration ?? base.narration ?? []).map((n) => ({ ...n, at: n.at - from })).filter((n) => n.at >= 0 && n.at < e.dur);
    narr.forEach((n) => rows.push({ t: t0 + n.at, n, end: t0 + e.dur }));
    t0 += e.dur;
  }
  rows.forEach((r, i) => {
    const next = i + 1 < rows.length ? Math.min(rows[i + 1].t, r.end) : r.end;
    md += `| ${mmss(r.t)} | ${r.n.id} | ${r.n.text} | ${(man.durations[r.n.id] ?? 0).toFixed(1)} s | ${(next - r.t).toFixed(1)} s |\n`;
  });
  md += `\nTotal running time: ${mmss(t0)}\n`;
}
fs.writeFileSync(path.join(ROOT, "script.md"), md);
console.log("script.md written");
